import { AudioTools, FileBridge } from '../../../services/native';
import { paths } from '../../../services/storage/paths';
import { musicRepo } from '../../../services/db/repositories';
import { logger } from '../../../services/logging/logger';

/**
 * Background loops shipped inside the APK (assets/music). They are generated
 * from code by tools/music/generate-music.mjs — no third-party audio — and
 * released as CC0, so users may publish audio that uses them freely.
 */
export const BUNDLED_MUSIC = [
  { id: 'bundled-calm-ambient', name: 'Calm Ambient', asset: 'music/calm-ambient.wav' },
  { id: 'bundled-light-electronic', name: 'Light Electronic Ambient', asset: 'music/light-electronic-ambient.wav' },
  { id: 'bundled-soft-keys', name: 'Soft Keys', asset: 'music/soft-keys.wav' },
  { id: 'bundled-tech-focus', name: 'Tech Focus', asset: 'music/tech-focus.wav' },
] as const;

const LICENSE = 'CC0-1.0';
const ATTRIBUTION = 'Generated by Voice Studio (tools/music/generate-music.mjs). No attribution required.';

/**
 * Makes sure every bundled track is in the library and on disk. Cheap when
 * nothing is missing; repairs itself after "delete everything" or a crash.
 */
export async function ensureBundledMusic(): Promise<void> {
  const existing = new Map((await musicRepo.list()).map(t => [t.id, t]));
  for (const track of BUNDLED_MUSIC) {
    const filePath = paths().musicTrack(track.id);
    try {
      const row = existing.get(track.id);
      if (row && row.filePath === filePath && (await FileBridge.exists(filePath))) {
        continue;
      }
      await FileBridge.mkdirs(paths().music);
      await FileBridge.copyAsset(track.asset, filePath);
      const info = await AudioTools.getAudioInfo(filePath);
      await musicRepo.upsert({
        id: track.id,
        name: track.name,
        filePath,
        durationMs: info.durationMs,
        sampleRate: info.sampleRate,
        source: 'bundled',
        license: LICENSE,
        attribution: ATTRIBUTION,
      });
    } catch {
      // A missing bundled loop must never block app start.
      logger.warn('music.bundled_failed', { id: track.id });
    }
  }
}
